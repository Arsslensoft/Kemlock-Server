pub(super) fn owner_param(raw: &str) -> Result<Owner, Problem> {
    raw.parse::<Owner>().map_err(Problem::bad_request)
}

pub(super) fn manifest_problem(e: ManifestError) -> Problem {
    match e {
        ManifestError::Stale { current } => Problem::new(
            StatusCode::CONFLICT,
            "stale-manifest",
            "The manifest's counter is not above the stored one",
        )
        .with("currentCounter", json!(current)),
        ManifestError::App(e) => e.into(),
        ManifestError::Space(e) => e.into(),
    }
}

fn method_name(method: TwoFactorMethod) -> &'static str {
    method.as_str()
}

