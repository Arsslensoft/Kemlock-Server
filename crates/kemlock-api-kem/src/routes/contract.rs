//! What the Kemlock app's sync client needs beyond items and sync: the signed manifest, the device
//! list, the one-time move of a Compatible account to OPAQUE, and the account's keys.
//!
//! - `PUT` and `GET /kem/v1/manifests/{owner}`: the signed manifest of an owner's items (the routes
//!   are in `manifests.rs`, which also serves a space's; the request and response shapes and the
//!   OpenAPI entries stay here).
//! - `GET /kem/v1/devices`: the account's devices, with each API's last use.
//! - `POST /kem/v1/auth/bitwarden/start` and `/finish`: a Compatible account sends its Bitwarden
//!   master password hash once and enrols OPAQUE in the same exchange.
//! - `GET /kem/v1/account/keys`: the wrapped root key, public bundle, signature and sealed private
//!   keys, for a browser that has none of them yet.
//! - `POST /kem/v1/account/keys/enrol`: the first keys of an account that single sign-on made with
//!   none, generated by the device, with that device's trusted-device copy of the root key.

