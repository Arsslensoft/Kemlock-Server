impl<S, P, K> Api<S, P, K>
where
    S: Store + DevicesStore + ManifestRepo + BwAccountRepo,
    P: Crypto,
    K: TokenSigner + Clone + 'static,
{
    fn device_list(&self) -> ListDevices<S, S, S> {
        ListDevices {
            devices: self.store.clone(),
            uses: self.store.clone(),
            copies: self.store.clone(),
        }
    }

    fn account_keys(&self) -> AccountKeys<S> {
        AccountKeys {
            users: self.store.clone(),
        }
    }

    fn enrol_keys(&self) -> EnrolKeys<S, S, S, P, S> {
        EnrolKeys {
            users: self.store.clone(),
            devices: self.store.clone(),
            copies: self.store.clone(),
            clock: self.crypto.clone(),
            events: self.store.clone(),
        }
    }

    fn bitwarden_enrol(&self) -> BitwardenEnrol<S, S, Pbkdf2Check, P, P, S, P, S, P> {
        BitwardenEnrol {
            users: self.store.clone(),
            accounts: self.store.clone(),
            check: Pbkdf2Check,
            auth: self.crypto.clone(),
            seal: self.crypto.clone(),
            two_factor: self.store.clone(),
            totp: self.crypto.clone(),
            events: self.store.clone(),
            env: self.crypto.clone(),
            config: self.auth_config(),
        }
    }
}

