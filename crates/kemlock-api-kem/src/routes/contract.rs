// Handlers.

impl<S, P, K> Api<S, P, K>
where
    S: Store + DevicesStore + ManifestRepo + BwAccountRepo,
    P: Crypto,
    K: TokenSigner + Clone + 'static,
{
    /// `GET /kem/v1/devices`: the account's devices.
    pub(crate) async fn handle_devices_list(
        State(api): State<Self>,
        authed: Authed,
    ) -> Result<Json<DeviceListResponse>, Problem> {
        let entries = api.device_list().execute(&authed.actor).await?;
        Ok(Json(DeviceListResponse {
            devices: entries
                .into_iter()
                .map(DeviceListEntry::from_entry)
                .collect(),
        }))
    }

    /// `GET /kem/v1/account/keys`: the account's wrapped and public key material.
    pub(crate) async fn handle_account_keys(
        State(api): State<Self>,
        authed: Authed,
    ) -> Result<Json<AccountKeysResponse>, Problem> {
        let keys = api.account_keys().execute(authed.actor.user).await?;
        Ok(Json(AccountKeysResponse {
            key_version: keys.key_version,
            kdf: KdfDto::from_params(&keys.kdf),
            wrapped_root_key: b64url::encode(&keys.wrapped_root_key),
            public_bundle: b64url::encode(&keys.public_bundle),
            bundle_signature: b64url::encode(&keys.bundle_signature),
            sealed_private_keys: b64url::encode(&keys.sealed_private_keys),
        }))
    }

    /// `POST /kem/v1/account/keys/enrol`: the first keys of an account that has none. 409 once it
    /// has them.
    pub(crate) async fn handle_enrol_keys(
        State(api): State<Self>,
        authed: Authed,
        body: Body,
    ) -> Result<Json<EnrolKeysResponse>, Problem> {
        guard(&api.limits.sign_in, &ip_key(authed.ip), api.now())?;
        let request: EnrolKeysRequest = body.json()?;
        let key_version = api
            .enrol_keys()
            .execute(
                &authed.actor,
                EnrolKeysInput {
                    public_bundle: decode("publicBundle", &request.public_bundle)?,
                    bundle_signature: decode("bundleSignature", &request.bundle_signature)?,
                    sealed_private_keys: decode("sealedPrivateKeys", &request.sealed_private_keys)?,
                    device_copy: decode("deviceCopy.wrappedKey", &request.device_copy.wrapped_key)?,
                    protection: request.device_copy.protection,
                },
            )
            .await?;
        Ok(Json(EnrolKeysResponse { key_version }))
    }

    /// `POST /kem/v1/auth/bitwarden/start`: checks the Bitwarden master password hash of a
    /// Compatible account and answers OPAQUE's first registration message. Limited per address
    /// and, for a wrong hash, per account (10 in 15 minutes, then doubling delays) under a key of
    /// its own, so guessing a hash never locks the account out of OPAQUE.
    pub(crate) async fn handle_bitwarden_start(
        State(api): State<Self>,
        proof: Proof,
        body: Body,
    ) -> Result<Json<BitwardenStartResponse>, Problem> {
        let request: BitwardenStartRequest = body.json()?;
        if request.email.len() > Email::MAX_LEN {
            return Err(Problem::bad_request("the email is too long"));
        }
        if request.master_password_hash.len() > MAX_PASSWORD_HASH_LEN {
            return Err(Problem::bad_request("the master password hash is too long"));
        }
        let now = api.now();
        guard(&api.limits.sign_in, &ip_key(proof.ip), now)?;
        // Wrong hashes count per account and source address, reserved before the hash is looked
        // at, as wrong passwords do.
        let attempt = attempts::begin_password_attempt(
            &api,
            "bwhash",
            &credential_id(&request.email),
            proof.ip,
        )
        .await?;
        let started = api
            .bitwarden_enrol()
            .start(EnrolStartInput {
                email: request.email,
                master_password_hash: request.master_password_hash,
                request: decode("request", &request.request)?,
                jkt: proof.jkt,
            })
            .await;
        attempts::end_password_attempt(&api, &attempt, &started);
        let started = started?;
        Ok(Json(BitwardenStartResponse {
            user_id: started.user.0,
            key: started.key,
            response: b64url::encode(&started.response),
            ticket: b64url::encode(&started.ticket),
            two_factor: started
                .two_factor
                .into_iter()
                .map(|m| method_name(m).to_owned())
                .collect(),
        }))
    }

    /// `POST /kem/v1/auth/bitwarden/finish`: OPAQUE's last registration message and the account's
    /// keys. A wrong second-step code counts against the account like at sign-in (5 in 15
    /// minutes, then doubling delays).
    pub(crate) async fn handle_bitwarden_finish(
        State(api): State<Self>,
        proof: Proof,
        body: Body,
    ) -> Result<StatusCode, Problem> {
        let request: BitwardenFinishRequest = body.json()?;
        let now = api.now();
        guard(&api.limits.sign_in, &ip_key(proof.ip), now)?;
        let ticket = decode("ticket", &request.ticket)?;
        let enrol = api.bitwarden_enrol();
        let user = enrol.ticket_user(&ticket)?;
        // Reserved before the code is looked at, so parallel guesses can't all get past the limit.
        attempts::reserve_second_step(&api, user, now).await?;
        let finished = enrol
            .finish(EnrolFinishInput {
                ticket,
                upload: decode("upload", &request.upload)?,
                kdf: request.kdf.to_params()?,
                public_bundle: decode("publicBundle", &request.public_bundle)?,
                bundle_signature: decode("bundleSignature", &request.bundle_signature)?,
                sealed_private_keys: decode("sealedPrivateKeys", &request.sealed_private_keys)?,
                wrapped_root_key: decode("wrappedRootKey", &request.wrapped_root_key)?,
                two_factor_code: request.two_factor_code,
                jkt: proof.jkt,
            })
            .await;
        attempts::settle_second_step(&api, user, &finished).await;
        finished?;
        Ok(StatusCode::NO_CONTENT)
    }
}

/// The routes of this module. Merged into the main router by `service::router`.
pub(crate) fn router<S, P, K>() -> Router<Api<S, P, K>>
where
    S: Store + DevicesStore + ManifestRepo + BwAccountRepo,
    P: Crypto,
    K: TokenSigner + Clone + 'static,
{
    type A<S, P, K> = Api<S, P, K>;
    Router::new()
        .route("/kem/v1/devices", get(A::<S, P, K>::handle_devices_list))
        .route(
            "/kem/v1/auth/bitwarden/start",
            post(A::<S, P, K>::handle_bitwarden_start),
        )
        .route(
            "/kem/v1/auth/bitwarden/finish",
            post(A::<S, P, K>::handle_bitwarden_finish),
        )
        .route(
            "/kem/v1/account/keys",
            get(A::<S, P, K>::handle_account_keys),
        )
        .route(
            "/kem/v1/account/keys/enrol",
            post(A::<S, P, K>::handle_enrol_keys),
        )
}

