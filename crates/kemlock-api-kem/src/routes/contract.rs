#[derive(Debug, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct ManifestRequest {
    /// The manifest's exact bytes (docs/crypto.md, "Signed manifest"), base64url. The counter is
    /// read from them.
    pub(crate) manifest: String,
    /// The `sig1` signature over the bytes under context `"manifest"`, 3,373 bytes, base64url.
    pub(crate) signature: String,
}

#[derive(Debug, Serialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub(crate) struct ManifestResponse {
    /// `user:<uuid>` or `space:<uuid>`.
    pub(crate) owner: String,
    pub(crate) counter: u64,
    /// The signed bytes, as stored, base64url.
    pub(crate) manifest: String,
    pub(crate) signature: String,
    /// The account whose bundle's `sig1` key signed it.
    pub(crate) signer: Uuid,
    pub(crate) stored_at: String,
}

impl ManifestResponse {
    pub(super) fn from_manifest(m: &SignedManifest) -> Self {
        ManifestResponse {
            owner: m.owner.to_string(),
            counter: m.counter,
            manifest: b64url::encode(&m.bytes),
            signature: b64url::encode(&m.signature),
            signer: m.signer.0,
            stored_at: rfc3339(m.stored_at).unwrap_or_default(),
        }
    }
}

#[derive(Debug, Serialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub(crate) struct DeviceListEntry {
    pub(crate) id: Uuid,
    pub(crate) name: String,
    #[schema(value_type = String)]
    pub(crate) kind: DeviceKind,
    pub(crate) created_at: String,
    /// The latest sign-in, refresh or use of either API.
    pub(crate) last_seen_at: String,
    /// The last authenticated request on the Kemlock API; absent when there was none.
    pub(crate) last_kemlock_use_at: Option<String>,
    /// The last authenticated request on the Bitwarden API; absent when there was none.
    pub(crate) last_bitwarden_use_at: Option<String>,
    /// Whether this is the device that asked.
    pub(crate) current: bool,
    /// Whether the device keeps a trusted-device copy of the root key on the server.
    pub(crate) trusted: bool,
    /// When the device made that copy; absent when it holds none.
    pub(crate) trusted_since: Option<String>,
}

impl DeviceListEntry {
    fn from_entry(e: DeviceEntry) -> Self {
        DeviceListEntry {
            id: e.id.0,
            name: e.name,
            kind: e.kind,
            created_at: rfc3339(e.created_at).unwrap_or_default(),
            last_seen_at: rfc3339(e.last_seen_at).unwrap_or_default(),
            last_kemlock_use_at: e.last_kemlock_use_at.and_then(rfc3339),
            last_bitwarden_use_at: e.last_bitwarden_use_at.and_then(rfc3339),
            current: e.current,
            trusted: e.trusted,
            trusted_since: e.trusted_since.and_then(rfc3339),
        }
    }
}

