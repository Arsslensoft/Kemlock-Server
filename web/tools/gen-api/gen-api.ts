// Generates src/api/schema.gen.d.ts from the running server's OpenAPI document. The hand-written
// client in src/api/client.ts takes its wire types from src/api/types.ts, which src/api/wire.check.ts
// ties to the generated `components["schemas"]` so a changed route breaks the build.
//
//   npm run gen:api                            # http://localhost:8000/kem/v1/openapi.json
//   KEMLOCK_URL=https://vault.example.org npm run gen:api
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const base = process.env.KEMLOCK_URL ?? 'http://localhost:8000';
const source = new URL('/kem/v1/openapi.json', base);
const ast = await openapiTS(source);
const out = fileURLToPath(new URL('../../src/api/schema.gen.d.ts', import.meta.url));
writeFileSync(out, `// Generated by tools/gen-api/gen-api.ts from ${source.href}. Do not edit.\n${astToString(ast)}`);
console.log(`wrote ${out}`);
