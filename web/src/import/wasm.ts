// The shape of the wasm-bindgen module built from crates/kemlock-import-wasm (web/scripts/build-wasm.sh
// writes it to ./pkg), and the loader that starts it. The interface is written by hand so the worker
// type-checks and its tests run before the module is built.

/**
 * What the module exports (crates/kemlock-import-wasm/src/wasm.rs). Each throws an `Error` whose
 * message is an `ImportErrorCode` of ./contract.ts.
 */
export interface ImportWasm {
  /** `{"format": "...", "encrypted": true}`, as JSON text. */
  detect(bytes: Uint8Array): string;
  /** The `ImportBatch` as JSON text. */
  parse(bytes: Uint8Array, format?: string, password?: string, keyFile?: Uint8Array): string;
  /** The bytes of a password-protected export of `kind` (`kemlock-json` or `bitwarden-json`). */
  exportEncrypted(kind: string, itemsJson: string, password: string): Uint8Array;
}

/** Starts the WebAssembly module. */
export type ImportWasmLoader = () => Promise<ImportWasm>;

export const loadImportWasm: ImportWasmLoader = async () => {
  // The module is generated by scripts/build-wasm.sh, so it is absent until that has run.
  // eslint-disable-next-line @typescript-eslint/ban-ts-comment
  // @ts-ignore
  const module = (await import('./pkg/kemlock_import_wasm.js')) as {
    default: () => Promise<unknown>;
  } & ImportWasm;
  await module.default();
  return {
    detect: (bytes) => module.detect(bytes),
    parse: (bytes, format, password, keyFile) => module.parse(bytes, format, password, keyFile),
    exportEncrypted: (kind, itemsJson, password) => module.exportEncrypted(kind, itemsJson, password),
  };
};
